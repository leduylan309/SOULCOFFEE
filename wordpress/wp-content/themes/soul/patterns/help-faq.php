<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Mua nhân xanh tối thiểu bao nhiêu?</summary><!-- wp:paragraph -->
<p>Bán lẻ mẫu 1 kg và 5 kg. Trên 60 kg, liên hệ để nhận báo giá theo lô. Giá nhân xanh chưa gồm 5% VAT. <a href="/coffee-solutions/#contact">Giải pháp cà phê →</a></p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Soul có cung cấp cà phê cho quán, nhà hàng, khách sạn không?</summary><!-- wp:paragraph -->
<p>Có. Dòng HORECA đóng gói 1 kg, kèm tư vấn công thức và setup quầy. Xưởng rang tại Buôn Ma Thuột đáp ứng trung bình 20 tấn mỗi tháng.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Có xuất hóa đơn VAT không?</summary><!-- wp:paragraph -->
<p>Có. Chọn “Xuất hóa đơn VAT” ở bước thanh toán, điền thông tin công ty và email nhận hóa đơn. Hóa đơn được xuất trong vòng 48 giờ (không gồm Thứ 7, Chủ nhật, ngày lễ) kể từ khi thanh toán thành công.</p>
