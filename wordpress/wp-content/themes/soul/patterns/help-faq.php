<details class="wp-block-details is-style-faq"><summary>Phí giao hàng là bao nhiêu?</summary><!-- wp:paragraph -->
<p>Giao tiêu chuẩn 30.000₫ (2–4 ngày làm việc), miễn phí cho đơn từ 500.000₫. Giao nhanh 50.000₫ tại nội thành TP.HCM, Hà Nội, Đà Nẵng và Buôn Ma Thuột. <a href="/help/#shipping">Chính sách giao hàng →</a></p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Tôi có thể nhận hàng tại cửa hàng không?</summary><!-- wp:paragraph -->
<p>Có. Chọn “Nhận tại cửa hàng” khi thanh toán để nhận miễn phí tại Soul Hồ Chí Minh, Buôn Ma Thuột, Hà Nội hoặc Đà Nẵng. Soul sẽ báo khi đơn sẵn sàng.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Làm sao theo dõi đơn hàng?</summary><!-- wp:paragraph -->
<p>Đăng nhập tài khoản và mở mục Đơn hàng để xem trạng thái. Nếu đặt không cần tài khoản, hãy liên hệ hotline kèm mã đơn.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

