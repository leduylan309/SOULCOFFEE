<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Nên chọn nguyên hạt hay xay sẵn?</summary><!-- wp:paragraph -->
<p>Nguyên hạt giữ hương lâu hơn nếu bạn có máy xay. Chọn xay sẵn khi mua theo cách pha (phin, pha máy, pour over, cold brew): Soul xay theo độ mịn phù hợp với từng dòng.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Bảo quản cà phê thế nào?</summary><!-- wp:paragraph -->
<p>Đóng kín túi, để nơi khô ráo, tránh ánh nắng và không cho vào tủ lạnh. Ngon nhất trong 4–6 tuần sau ngày rang in trên bao bì.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Fine Robusta khác Robusta thông thường ra sao?</summary><!-- wp:paragraph -->
<p>Fine Robusta được hái chín, sơ chế và chấm điểm theo tiêu chuẩn đặc sản, cho vị ngọt, sạch và nhiều tầng hương hơn Robusta thương mại. <a href="/blog/category/how-to-make-coffee/">Hướng dẫn pha →</a></p>
