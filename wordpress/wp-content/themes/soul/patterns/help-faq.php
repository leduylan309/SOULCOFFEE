<details class="wp-block-details is-style-faq"><summary>Soul có bán trên sàn thương mại điện tử không?</summary><!-- wp:paragraph -->
<p>Có, Soul có gian hàng chính thức trên Shopee và Lazada. Một số dòng theo mùa và nhân xanh chỉ bán trên website.</p>
